DROP POLICY IF EXISTS staff_parameters_select ON public.staff_parameters;
DROP POLICY IF EXISTS staff_parameters_admin  ON public.staff_parameters;
CREATE POLICY staff_parameters_select ON public.staff_parameters
  FOR SELECT TO authenticated USING (true);
CREATE POLICY staff_parameters_admin ON public.staff_parameters
  FOR ALL TO authenticated USING (is_admin()) WITH CHECK (is_admin());

DROP POLICY IF EXISTS staff_members_select ON public.staff_members;
DROP POLICY IF EXISTS staff_members_insert ON public.staff_members;
DROP POLICY IF EXISTS staff_members_update ON public.staff_members;
DROP POLICY IF EXISTS staff_members_delete ON public.staff_members;
CREATE POLICY staff_members_select ON public.staff_members
  FOR SELECT TO authenticated
  USING (user_can_access_staff(scenario_id, home_cost_center_id, id));
CREATE POLICY staff_members_insert ON public.staff_members
  FOR INSERT TO authenticated
  WITH CHECK (user_can_access_staff(scenario_id, home_cost_center_id, id));
-- Both USING and WITH CHECK — an UPDATE policy without WITH CHECK rejects the new row silently.
CREATE POLICY staff_members_update ON public.staff_members
  FOR UPDATE TO authenticated
  USING (user_can_access_staff(scenario_id, home_cost_center_id, id))
  WITH CHECK (user_can_access_staff(scenario_id, home_cost_center_id, id));
CREATE POLICY staff_members_delete ON public.staff_members
  FOR DELETE TO authenticated
  USING (user_can_access_staff(scenario_id, home_cost_center_id, id));

DROP POLICY IF EXISTS staff_periods_all ON public.staff_periods;
CREATE POLICY staff_periods_all ON public.staff_periods
  FOR ALL TO authenticated
  USING (user_can_access_staff_member(member_id))
  WITH CHECK (user_can_access_staff_member(member_id));

DROP POLICY IF EXISTS staff_allocations_all ON public.staff_allocations;
CREATE POLICY staff_allocations_all ON public.staff_allocations
  FOR ALL TO authenticated
  USING (user_can_access_staff_member(member_id))
  WITH CHECK (user_can_access_staff_member(member_id));
