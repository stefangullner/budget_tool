-- Personalbudget: staff per scenario, calculated in the database and written to
-- the personnel accounts in budget_entries.
--
-- Design:
--   * ONE calculation — staff_cost_rows(). The staff view reads it, and
--     recalc_staff_budget() writes it to budget_entries. They cannot disagree.
--   * Recalculation runs in statement-level triggers, so every change to a person,
--     a period, an allocation or the parameters is in the budget as soon as the
--     write returns. A bulk import is one statement → one recalculation.
--   * The personnel accounts are locked: guard_staff_budget_entries() rejects any
--     write to them from the app. Only the recalculation (running as the function
--     owner) writes there.
--   * Visibility follows the existing scope rule via
--     user_can_access_company_cost_center(). A person is visible to anyone who can
--     see their home cost center or any cost center they are allocated to — and
--     those people may also change them (shared staff is editable by every
--     regional manager involved).
--
-- Foreign keys follow the FK delete rules decided 2026-09-16:
--   hand-entered data → NO ACTION against cost_centers, CASCADE from scenarios,
--   never SET NULL on scope columns, SET NULL on auth.users.
--
-- DDL only. Verification lives in verify_staff_budget.sql.

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.staff_parameters (
  scenario_id                  integer PRIMARY KEY REFERENCES public.scenarios(id) ON DELETE CASCADE,
  salary_increase_pct          numeric NOT NULL DEFAULT 3,
  salary_increase_from         date,                         -- NULL = no increase in this scenario
  vacation_supplement_pct      numeric NOT NULL DEFAULT 0.8, -- % of monthly salary per vacation day
  vacation_supplement_month    smallint CHECK (vacation_supplement_month BETWEEN 1 AND 12), -- NULL = spread evenly
  employer_fee_pct             numeric NOT NULL DEFAULT 31.42,
  pension_pct                  numeric NOT NULL DEFAULT 8.5,
  payroll_tax_pct              numeric NOT NULL DEFAULT 24.26,
  absence_pct                  numeric NOT NULL DEFAULT 0,   -- reduces salary cost for sick leave, VAB etc.
  cost_sign                    smallint NOT NULL DEFAULT 1 CHECK (cost_sign IN (1, -1)),
  account_salary               text NOT NULL DEFAULT '7210',
  account_vacation_supplement  text DEFAULT '7285',
  account_employer_fee         text DEFAULT '7510',
  account_pension              text DEFAULT '7410',
  account_payroll_tax          text DEFAULT '7530',
  account_car_benefit          text DEFAULT '7390',
  account_car_benefit_fee      text DEFAULT '7510',
  book_car_benefit_value       boolean NOT NULL DEFAULT false, -- the benefit value itself is usually offset, only the fee is a cost
  default_salaries             jsonb NOT NULL DEFAULT '{}'::jsonb, -- { "<title>": <starting salary> } for recruitments
  -- Rollout switch. 'company_managers': only admins and the company's managers see
  -- and edit staff. 'everyone': anyone with scope on the person's cost centers.
  visibility                   text NOT NULL DEFAULT 'company_managers'
                               CHECK (visibility IN ('company_managers', 'everyone')),
  updated_by                   uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_at                   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.staff_members (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scenario_id          integer NOT NULL REFERENCES public.scenarios(id) ON DELETE CASCADE,
  employee_no          text,
  first_name           text NOT NULL DEFAULT '',
  last_name            text NOT NULL DEFAULT '',
  title                text,
  employment_type      text CHECK (employment_type IN ('TV', 'PRO', 'TID')),
  is_recruitment       boolean NOT NULL DEFAULT false,
  home_cost_center_id  integer NOT NULL REFERENCES public.cost_centers(id) ON DELETE NO ACTION,
  included             boolean NOT NULL DEFAULT true,
  employment_rate      numeric NOT NULL DEFAULT 100 CHECK (employment_rate BETWEEN 0 AND 100),
  monthly_salary       numeric NOT NULL DEFAULT 0 CHECK (monthly_salary >= 0),
  supplement           numeric NOT NULL DEFAULT 0,
  vacation_days        smallint NOT NULL DEFAULT 25 CHECK (vacation_days BETWEEN 0 AND 60),
  car_benefit          numeric NOT NULL DEFAULT 0 CHECK (car_benefit >= 0), -- benefit value per year
  note                 text,
  reviewed_by          uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at          timestamptz,
  updated_by           uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  updated_at           timestamptz NOT NULL DEFAULT now(),
  UNIQUE (scenario_id, employee_no)
);
CREATE INDEX IF NOT EXISTS staff_members_scenario_idx ON public.staff_members (scenario_id);
CREATE INDEX IF NOT EXISTS staff_members_home_cc_idx  ON public.staff_members (home_cost_center_id);

-- Everything that varies during the year. Replaces the free-text comments and the
-- hand-edited month cells in the Excel file. Overlaps: the latest start wins.
CREATE TABLE IF NOT EXISTS public.staff_periods (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  member_id    integer NOT NULL REFERENCES public.staff_members(id) ON DELETE CASCADE,
  from_period  date NOT NULL,  -- first day of the month
  to_period    date NOT NULL,  -- first day of the month, inclusive
  rate         numeric NOT NULL CHECK (rate BETWEEN 0 AND 100),
  reason       text,
  CHECK (to_period >= from_period)
);
CREATE INDEX IF NOT EXISTS staff_periods_member_idx ON public.staff_periods (member_id);

-- Salary split across cost centers. No rows = 100 % on the home cost center.
-- Shares are normalised in the calculation, so 17 + 11 + … need not hit exactly 100.
-- scenario_id is denormalised so the recalculation still knows the scenario when
-- a row disappears through a cascade from staff_members.
CREATE TABLE IF NOT EXISTS public.staff_allocations (
  member_id       integer NOT NULL REFERENCES public.staff_members(id) ON DELETE CASCADE,
  cost_center_id  integer NOT NULL REFERENCES public.cost_centers(id) ON DELETE NO ACTION,
  share           numeric NOT NULL CHECK (share >= 0),
  scenario_id     integer NOT NULL REFERENCES public.scenarios(id) ON DELETE CASCADE,
  PRIMARY KEY (member_id, cost_center_id)
);
CREATE INDEX IF NOT EXISTS staff_allocations_cc_idx ON public.staff_allocations (cost_center_id);

-- Rows written by the recalculation have no human author when it runs outside a
-- request (SQL editor). NULL is the honest value there.
ALTER TABLE public.budget_entries ALTER COLUMN updated_by DROP NOT NULL;

