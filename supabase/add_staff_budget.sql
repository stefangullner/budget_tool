-- Parameters: turning the staff budget on, or changing a rate, recalculates the
-- whole scenario. Changing an account number first clears the old account, which
-- would otherwise keep stale amounts that nobody can edit any more.
CREATE OR REPLACE FUNCTION public.staff_parameters_recalc()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  v_company integer;
BEGIN
  IF TG_OP = 'DELETE' THEN
    RETURN NULL; -- turning it off keeps the amounts as ordinary, editable entries
  END IF;
  IF TG_OP = 'UPDATE' THEN
    SELECT company_id INTO v_company FROM scenarios WHERE id = OLD.scenario_id;
    DELETE FROM budget_entries be
    USING accounts a
    WHERE be.scenario_id = OLD.scenario_id
      AND a.id = be.account_id
      AND a.company_id = v_company
      AND a.account_number IN (
        OLD.account_salary, OLD.account_vacation_supplement, OLD.account_employer_fee,
        OLD.account_pension, OLD.account_payroll_tax, OLD.account_car_benefit,
        OLD.account_car_benefit_fee
      );
  END IF;
  PERFORM recalc_staff_budget(NEW.scenario_id, NULL);
  RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS staff_parameters_recalc ON public.staff_parameters;
CREATE TRIGGER staff_parameters_recalc
  AFTER INSERT OR UPDATE OR DELETE ON public.staff_parameters
  FOR EACH ROW EXECUTE FUNCTION public.staff_parameters_recalc();

