-- Company managers of the scenario's company (a NULL company_id on the role means
-- every company, same as in the other policies).
CREATE OR REPLACE FUNCTION public.user_is_company_manager_for(p_company_id integer)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM user_roles ur
    WHERE ur.user_id = auth.uid()
      AND ur.role = 'company_manager'
      AND (ur.company_id IS NULL OR ur.company_id = p_company_id)
  )
$$;

-- Who may see and change a person.
--   visibility = 'company_managers' (the default while rolling out): admins and the
--     company's managers only.
--   visibility = 'everyone': also anyone who can see the person's home cost center
--     or any cost center they are allocated to.
-- SECURITY DEFINER so the lookups are not themselves filtered by RLS (circular).
CREATE OR REPLACE FUNCTION public.user_can_access_staff(
  p_scenario_id integer,
  p_home_cost_center_id integer,
  p_member_id integer
)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT is_admin() OR EXISTS (
    SELECT 1 FROM scenarios s
    JOIN staff_parameters sp ON sp.scenario_id = s.id
    WHERE s.id = p_scenario_id
      AND (
        user_is_company_manager_for(s.company_id)
        OR (
          sp.visibility = 'everyone'
          AND (
            user_can_access_company_cost_center(s.company_id, p_home_cost_center_id)
            OR EXISTS (
              SELECT 1 FROM staff_allocations a
              WHERE a.member_id = p_member_id
                AND user_can_access_company_cost_center(s.company_id, a.cost_center_id)
            )
          )
        )
      )
  )
$$;

CREATE OR REPLACE FUNCTION public.user_can_access_staff_member(p_member_id integer)
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT COALESCE(
    (SELECT user_can_access_staff(m.scenario_id, m.home_cost_center_id, m.id)
     FROM staff_members m WHERE m.id = p_member_id),
    false
  )
$$;

