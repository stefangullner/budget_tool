  REFERENCING OLD TABLE AS old_rows FOR EACH STATEMENT EXECUTE FUNCTION public.staff_allocations_recalc_old();

CREATE OR REPLACE FUNCTION public.staff_periods_recalc()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  r record;
BEGIN
  FOR r IN
    WITH touched AS (
      SELECT member_id FROM new_rows WHERE TG_OP <> 'DELETE'
    )
    SELECT x.scenario_id, array_agg(DISTINCT x.cc) AS ccs FROM (
      SELECT m.scenario_id, m.home_cost_center_id AS cc FROM staff_members m WHERE m.id IN (SELECT member_id FROM touched)
      UNION SELECT a.scenario_id, a.cost_center_id FROM staff_allocations a WHERE a.member_id IN (SELECT member_id FROM touched)
    ) x GROUP BY x.scenario_id
  LOOP
    PERFORM recalc_staff_budget(r.scenario_id, r.ccs);
  END LOOP;
  RETURN NULL;
END $$;

CREATE OR REPLACE FUNCTION public.staff_periods_recalc_old()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  r record;
BEGIN
  -- A member deleted in the same statement no longer resolves; the member's own trigger covers it.
  FOR r IN
    SELECT x.scenario_id, array_agg(DISTINCT x.cc) AS ccs FROM (
      SELECT m.scenario_id, m.home_cost_center_id AS cc FROM staff_members m WHERE m.id IN (SELECT member_id FROM old_rows)
      UNION SELECT a.scenario_id, a.cost_center_id FROM staff_allocations a WHERE a.member_id IN (SELECT member_id FROM old_rows)
    ) x GROUP BY x.scenario_id
  LOOP
    PERFORM recalc_staff_budget(r.scenario_id, r.ccs);
  END LOOP;
  RETURN NULL;
END $$;

DROP TRIGGER IF EXISTS staff_periods_recalc_ins ON public.staff_periods;
DROP TRIGGER IF EXISTS staff_periods_recalc_upd ON public.staff_periods;
DROP TRIGGER IF EXISTS staff_periods_recalc_del ON public.staff_periods;
